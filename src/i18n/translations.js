export function getTranslations(lang) {
  return DICT[lang] || DICT.en;
}

export function t(lang, key) {
  const dict = getTranslations(lang);
  return dict[key] || DICT.en[key] || key;
}

export function isRtl(lang) {
  return lang === 'ur';
}

export function sectionTitle(lang, sectionId, fallback) {
  const entry = SECTION_TITLES[sectionId];
  if (!entry) return fallback || sectionId;
  return entry[lang] || entry.en || fallback || sectionId;
}

export function heroSlide(lang, index) {
  const slide = HERO_I18N[index];
  if (!slide) return HERO_I18N[0].en;
  return slide[lang] || slide.en;
}

export function heroSlideCount() {
  return HERO_I18N.length;
}
